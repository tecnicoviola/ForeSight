"""
Module 3: Product Analytics Page.
Redesigned with Linear / Stripe SaaS visual hierarchy:
- Segmented ranking controls (Revenue vs Volume)
- Protected KPI card titles preventing text wrapping
- Value vs Volume matrix and Pareto concentration curve
- Filtered, search-enabled catalog performance table
"""

import sys
from pathlib import Path
import streamlit as st
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go

BASE_DIR = Path(__file__).resolve().parent.parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

from src.data.loader import load_product_sales
from src.analytics.product_analysis import get_top_products, compute_pareto_distribution
from src.utils.helpers import (
    format_currency,
    format_number,
    format_percentage,
    apply_theme_to_figure,
    render_kpi_card_html,
    render_page_header,
    get_current_theme,
)
from src.utils.config import CURRENCY_SYMBOL, APP_NAME
from src.utils.layout import (
    load_custom_css,
    render_sidebar_header,
    render_theme_segmented_control,
    render_sidebar_provenance,
)


def render_product_analytics():
    theme = get_current_theme()
    is_dark = theme["mode"] == "dark"

    # Section A: Header
    render_page_header(
        title="Product Analytics",
        description="Analyse product-level revenue, sales volume and catalog performance.",
        badge="Catalog Intelligence",
    )

    df_products = load_product_sales()
    pareto = compute_pareto_distribution(df_products)

    # Section B: 4 Equal-Height Catalog KPIs with Clean Truncation
    k1, k2, k3, k4 = st.columns(4)
    with k1:
        st.markdown(
            render_kpi_card_html(
                "Total Catalog SKUs",
                format_number(pareto["total_catalog_size"]),
                "Active unique product codes",
                badge="Catalog",
                badge_type="primary",
                accent_bar="#2563EB",
            ),
            unsafe_allow_html=True,
        )
    with k2:
        top_prod = df_products.iloc[0]
        # Clean truncation preventing multi-line break
        clean_name = top_prod['Description'][:24] + "..." if len(top_prod['Description']) > 24 else top_prod['Description']
        st.markdown(
            render_kpi_card_html(
                "Top Revenue SKU",
                format_currency(top_prod["Revenue"]),
                f"SKU {top_prod['StockCode']}: {clean_name}",
                badge="Leader",
                badge_type="success",
                accent_bar="#059669",
            ),
            unsafe_allow_html=True,
        )
    with k3:
        st.markdown(
            render_kpi_card_html(
                "Pareto 80% Threshold",
                f"{format_number(pareto['products_for_80_pct'])} SKUs",
                f"Generated by {pareto['pct_of_catalog_for_80_pct']}% of catalog items",
                badge="80/20 Rule",
                badge_type="warning",
                accent_bar="#D97706",
            ),
            unsafe_allow_html=True,
        )
    with k4:
        st.markdown(
            render_kpi_card_html(
                "Top 10% Revenue Share",
                f"{pareto['top_10_pct_revenue_share']}%",
                "Concentrated revenue volume",
                badge="Volume",
                badge_type="neutral",
                accent_bar="#8B5CF6",
            ),
            unsafe_allow_html=True,
        )

    st.markdown(f"<hr style='border:0; border-top:1px solid {theme['border']}; margin: 24px 0;'>", unsafe_allow_html=True)

    # Section C: Professional Segmented Ranking Controls
    col_ctrl1, col_ctrl2 = st.columns([2, 1])
    with col_ctrl1:
        ranking_metric = st.segmented_control(
            "Rank Catalog By",
            options=["Revenue", "Units Sold"],
            default="Revenue",
            format_func=lambda x: "Revenue (£)" if x == "Revenue" else "Units Sold (Quantity)",
            key="pa_ranking_metric_seg",
        )
    if not ranking_metric:
        ranking_metric = "Revenue"

    with col_ctrl2:
        top_n = st.selectbox("Display Top N Products:", [10, 15, 20, 30], index=0, key="pa_top_n_select")

    by_col = "Revenue" if ranking_metric == "Revenue" else "Quantity"
    top_df = get_top_products(df_products, by=by_col, top_n=top_n)

    # Section D: Top Products Ranking Visualization
    st.markdown(f"### Top {top_n} Products Ranked by {ranking_metric}")
    fig_top = go.Figure()
    fig_top.add_trace(
        go.Bar(
            x=top_df[by_col][::-1],
            y=top_df["Description"].str[:35][::-1],
            orientation="h",
            marker=dict(color=theme["primary"], cornerradius=3),
            hovertemplate=(
                "<b>%{y}</b><br>"
                + ("Revenue: " + CURRENCY_SYMBOL + "%{x:,.2f}" if by_col == "Revenue" else "Units Sold: %{x:,}")
                + "<extra></extra>"
            ),
        )
    )
    apply_theme_to_figure(fig_top, height=440)
    st.plotly_chart(fig_top, use_container_width=True)

    # Section E: Portfolio Value vs Volume Scatter Matrix
    st.markdown("### Product Portfolio Matrix: Sales Volume vs. Total Revenue")
    top_scatter = df_products.head(200).copy()
    fig_scatter = px.scatter(
        top_scatter,
        x="Quantity",
        y="Revenue",
        size="Transactions",
        hover_name="Description",
        hover_data={"StockCode": True, "AvgPrice": ":.2f", "Revenue": ":,.2f", "Quantity": ":,"},
        labels={"Quantity": "Total Units Sold", "Revenue": "Total Revenue (£)"},
        color_discrete_sequence=[theme["primary"]],
    )
    apply_theme_to_figure(fig_scatter, height=400)
    st.plotly_chart(fig_scatter, use_container_width=True)

    # Section F: Cumulative Pareto Revenue Concentration Curve
    st.markdown("### Cumulative Revenue Concentration (Pareto 80/20 Curve)")
    pareto_df = df_products.head(500).copy()
    fig_pareto = go.Figure()
    fig_pareto.add_trace(
        go.Scatter(
            x=pareto_df["Revenue_Rank"],
            y=pareto_df["Cumulative_Revenue_Pct"],
            mode="lines",
            line=dict(color=theme["accent"], width=2.5),
            name="Cumulative Revenue Share (%)",
            hovertemplate="<b>Rank %{x}</b><br>Cumulative Share: %{y:.2f}%<extra></extra>",
        )
    )
    fig_pareto.add_shape(
        type="line",
        x0=0,
        x1=len(pareto_df),
        y0=80,
        y1=80,
        line=dict(color=theme["danger"], dash="dash", width=1.5),
    )
    apply_theme_to_figure(fig_pareto, height=310)
    fig_pareto.update_layout(yaxis=dict(title="Cumulative Share (%)", range=[0, 105]))
    st.plotly_chart(fig_pareto, use_container_width=True)

    # Section G: Searchable Product Catalog Table
    st.markdown("### Product Catalog Performance Table")
    search_term = st.text_input("Search catalog by SKU or Description:", "", placeholder="Type SKU or product name...", key="pa_search_term")
    table_display = df_products.copy()
    if search_term:
        term = search_term.strip().lower()
        table_display = table_display[
            table_display["Description"].str.lower().str.contains(term, na=False)
            | table_display["StockCode"].str.lower().str.contains(term, na=False)
        ]

    formatted_table = table_display.head(50).copy()
    formatted_table["Revenue"] = formatted_table["Revenue"].apply(lambda v: format_currency(v))
    formatted_table["Quantity"] = formatted_table["Quantity"].apply(lambda v: format_number(v))
    formatted_table["AvgPrice"] = formatted_table["AvgPrice"].apply(lambda v: format_currency(v))
    formatted_table["Revenue_Contribution_Pct"] = formatted_table["Revenue_Contribution_Pct"].apply(
        lambda v: f"{v:.2f}%"
    )

    st.dataframe(
        formatted_table[
            ["Revenue_Rank", "StockCode", "Description", "Revenue", "Quantity", "AvgPrice", "Revenue_Contribution_Pct"]
        ].rename(
            columns={
                "Revenue_Rank": "Rank",
                "StockCode": "SKU",
                "Description": "Product Name",
                "Revenue": "Total Revenue (£)",
                "Quantity": "Units Sold",
                "AvgPrice": "Avg Unit Price (£)",
                "Revenue_Contribution_Pct": "Catalog Share (%)",
            }
        ),
        hide_index=True,
        use_container_width=True,
    )


if __name__ == "__main__":
    if "theme_mode" not in st.session_state:
        st.session_state["theme_mode"] = "Light"
    st.set_page_config(
        page_title=f"Product Analytics — {APP_NAME}",
        page_icon="✦",
        layout="wide",
        initial_sidebar_state="expanded",
    )
    load_custom_css()
    with st.sidebar:
        render_sidebar_header()
        render_theme_segmented_control()
        st.markdown("<hr style='border:0; border-top:1px solid var(--border-color, #E2E8F0); margin:14px 0;'>", unsafe_allow_html=True)
        render_sidebar_provenance()
    render_product_analytics()
