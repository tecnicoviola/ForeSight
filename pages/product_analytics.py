"""
Module 3: Product Analytics Page.
In-depth catalog performance rankings, volume vs. value analysis, and Pareto revenue concentration.
"""

import sys
from pathlib import Path
import streamlit as st
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go

BASE_DIR = Path(__file__).resolve().parent.parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

from src.data.loader import load_product_sales
from src.analytics.product_analysis import get_top_products, compute_pareto_distribution
from src.utils.helpers import (
    format_currency,
    format_number,
    format_percentage,
    apply_theme_to_figure,
    render_kpi_card_html,
)
from src.utils.config import THEME, CURRENCY_SYMBOL, APP_NAME
from src.utils.layout import load_custom_css, render_sidebar_header, render_sidebar_provenance


def render_product_analytics():
    st.markdown("## Product Analytics & Catalog Performance")
    st.markdown(
        "<p style='color:#64748B; font-size:14px; margin-top:-6px; margin-bottom:22px;'>"
        "Catalog performance analytics derived from 4,916 distinct retail products transacted across 2009–2011."
        "</p>",
        unsafe_allow_html=True,
    )

    df_products = load_product_sales()
    pareto = compute_pareto_distribution(df_products)

    # Catalog KPIs
    k1, k2, k3, k4 = st.columns(4)
    with k1:
        st.markdown(
            render_kpi_card_html(
                "Total Catalog SKUs",
                format_number(pareto["total_catalog_size"]),
                "Distinct active stock codes",
                badge="Catalog",
                badge_type="primary",
            ),
            unsafe_allow_html=True,
        )
    with k2:
        top_prod = df_products.iloc[0]
        st.markdown(
            render_kpi_card_html(
                "Top Revenue Driver",
                format_currency(top_prod["Revenue"]),
                f"SKU {top_prod['StockCode']}: {top_prod['Description'][:25]}...",
                badge="Leader",
                badge_type="success",
            ),
            unsafe_allow_html=True,
        )
    with k3:
        st.markdown(
            render_kpi_card_html(
                "Pareto 80% Threshold",
                f"{format_number(pareto['products_for_80_pct'])} SKUs",
                f"Generated by {pareto['pct_of_catalog_for_80_pct']}% of catalog items",
                badge="80/20 Rule",
                badge_type="warning",
            ),
            unsafe_allow_html=True,
        )
    with k4:
        st.markdown(
            render_kpi_card_html(
                "Top 10% SKU Revenue Share",
                f"{pareto['top_10_pct_revenue_share']}%",
                "High revenue concentration",
                badge="Concentration",
                badge_type="neutral",
            ),
            unsafe_allow_html=True,
        )

    st.markdown("<hr style='border:0; border-top:1px solid #E2E8F0; margin: 20px 0;'>", unsafe_allow_html=True)

    # Interactive Rankings Filter
    col_ctrl1, col_ctrl2 = st.columns([2, 1])
    with col_ctrl1:
        ranking_metric = st.radio("Rank Products By:", ["Revenue (£)", "Units Sold (Quantity)"], horizontal=True, key="prod_ranking_metric")
    with col_ctrl2:
        top_n = st.selectbox("Display Top N Products:", [10, 15, 20, 30], index=0, key="prod_top_n")

    by_col = "Revenue" if "Revenue" in ranking_metric else "Quantity"
    top_df = get_top_products(df_products, by=by_col, top_n=top_n)

    # Top Products Visualization
    st.markdown(f"### Top {top_n} Products Ranked by {ranking_metric}")
    fig_top = go.Figure()
    fig_top.add_trace(
        go.Bar(
            x=top_df[by_col][::-1],
            y=top_df["Description"].str[:38][::-1],
            orientation="h",
            marker=dict(color=THEME["primary"]),
            hovertemplate=(
                "<b>%{y}</b><br>"
                + ("Revenue: " + CURRENCY_SYMBOL + "%{x:,.2f}" if by_col == "Revenue" else "Units: %{x:,}")
                + "<extra></extra>"
            ),
        )
    )
    apply_theme_to_figure(fig_top, height=450)
    st.plotly_chart(fig_top, use_container_width=True)

    # Value vs Volume Analysis (Scatter Plot)
    st.markdown("### Product Portfolio Matrix: Volume Sold vs. Revenue Generated")
    top_scatter = df_products.head(200).copy()
    fig_scatter = px.scatter(
        top_scatter,
        x="Quantity",
        y="Revenue",
        size="Transactions",
        hover_name="Description",
        hover_data={"StockCode": True, "AvgPrice": ":.2f", "Revenue": ":,.2f", "Quantity": ":,"},
        labels={"Quantity": "Total Units Sold", "Revenue": "Total Revenue (£)"},
        color_discrete_sequence=[THEME["primary"]],
    )
    apply_theme_to_figure(fig_scatter, height=420)
    st.plotly_chart(fig_scatter, use_container_width=True)

    # Cumulative Pareto Curve
    st.markdown("### Cumulative Revenue Concentration (Pareto Curve)")
    pareto_df = df_products.head(500).copy()
    fig_pareto = go.Figure()
    fig_pareto.add_trace(
        go.Scatter(
            x=pareto_df["Revenue_Rank"],
            y=pareto_df["Cumulative_Revenue_Pct"],
            mode="lines",
            line=dict(color=THEME["accent"], width=2.5),
            name="Cumulative Revenue Share (%)",
            hovertemplate="<b>Rank %{x}</b><br>Cumulative Share: %{y:.2f}%<extra></extra>",
        )
    )
    # 80% line
    fig_pareto.add_shape(
        type="line",
        x0=0,
        x1=len(pareto_df),
        y0=80,
        y1=80,
        line=dict(color=THEME["danger"], dash="dash", width=1.5),
    )
    apply_theme_to_figure(fig_pareto, height=320)
    fig_pareto.update_layout(yaxis=dict(title="Cumulative Share (%)", range=[0, 105]))
    st.plotly_chart(fig_pareto, use_container_width=True)

    # Searchable Catalog Table
    st.markdown("### Product Catalog Search & Performance Table")
    search_term = st.text_input("Search catalog by SKU or Product Description:", "", key="prod_search_term")
    table_display = df_products.copy()
    if search_term:
        term = search_term.strip().lower()
        table_display = table_display[
            table_display["Description"].str.lower().str.contains(term, na=False)
            | table_display["StockCode"].str.lower().str.contains(term, na=False)
        ]

    formatted_table = table_display.head(50).copy()
    formatted_table["Revenue"] = formatted_table["Revenue"].apply(lambda v: format_currency(v))
    formatted_table["Quantity"] = formatted_table["Quantity"].apply(lambda v: format_number(v))
    formatted_table["AvgPrice"] = formatted_table["AvgPrice"].apply(lambda v: format_currency(v))
    formatted_table["Revenue_Contribution_Pct"] = formatted_table["Revenue_Contribution_Pct"].apply(
        lambda v: f"{v:.2f}%"
    )

    st.dataframe(
        formatted_table[
            ["Revenue_Rank", "StockCode", "Description", "Revenue", "Quantity", "AvgPrice", "Revenue_Contribution_Pct"]
        ].rename(
            columns={
                "Revenue_Rank": "Rank",
                "StockCode": "SKU",
                "Description": "Product Name",
                "Revenue": "Total Revenue (£)",
                "Quantity": "Units Sold",
                "AvgPrice": "Avg Unit Price (£)",
                "Revenue_Contribution_Pct": "Catalog Share (%)",
            }
        ),
        hide_index=True,
        use_container_width=True,
    )


if __name__ == "__main__":
    st.set_page_config(
        page_title=f"Product Analytics — {APP_NAME}",
        page_icon="📦",
        layout="wide",
        initial_sidebar_state="expanded",
    )
    load_custom_css()
    with st.sidebar:
        render_sidebar_header()
        st.markdown(
            f"<div style='background:#EFF6FF; border:1px solid #DBEAFE; border-radius:8px; padding:8px 12px; margin-bottom:12px;'>"
            f"<span style='font-size:13px; font-weight:700; color:{THEME['primary']};'>📦 Product Analytics</span>"
            f"</div>",
            unsafe_allow_html=True,
        )
        st.markdown("<hr style='border:0; border-top:1px solid #E2E8F0; margin:16px 0;'>", unsafe_allow_html=True)
        render_sidebar_provenance()
    render_product_analytics()
